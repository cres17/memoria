#!/usr/bin/env python3
"""Embed committed photos in the integration-test target only, never Runner."""
import base64
from pathlib import Path

root = Path(__file__).resolve().parents[1]
photos = [root / "test" / f"원본_{i}.jpg" for i in (1, 2)]
target = root / "integration_test" / "gpu_test_photos.g.dart"
target.write_text("// Generated by tool/prepare_gpu_test_photos.py. Test target only.\n"
                  "const gpuTestPhotos = <String>[\n" +
                  "".join("  '" + base64.b64encode(p.read_bytes()).decode() + "',\n" for p in photos) +
                  "];\n")
references = sorted((root / "test/visual/references").glob("*.png"))
with target.open("a") as output:
    output.write("const gpuVisualReferences = <String, String>{\n")
    for photo in references:
        output.write("  '" + photo.stem + "': '" + base64.b64encode(photo.read_bytes()).decode() + "',\n")
    output.write("};\n")
print(f"Prepared {len(photos)} photo fixtures: {target.name}")
